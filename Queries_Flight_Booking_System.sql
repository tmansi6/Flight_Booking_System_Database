--                identify the total number of baggage’s (which are checkedin) made on a specified date for a specific flight.
Create view BaggageSummary as
Select r.FlightId,t.IssueDate, count(b.BaggageId) as TotalBaggageCheckedIn
	from Baggage b inner join Ticket t on b.TicketId=t.TicketId inner join Reservation r on t.ReservationId=r.ReservationId
	where b.BaggageStatus='Checked-In' group by r.FlightId,t.IssueDate

