Select p.PassengerId,p.FirstName,p.LastName, DATEDIFF(YEAR,p.DateOfBirth,GETDATE()) as age
		from Passenger p join Reservation r on p.PassengerId=r.PassengerId
		where DATEDIFF(YEAR,p.DateOfBirth,GETDATE())>40 and r.BookingStatus='Pending';

-- ques 2: a) Search the database of the ticketing system for matching character strings by last name of passenger. 
--                  Results should be sorted with most recent issued ticket first.
Create procedure SearchPassengerByLastName
	@LastName nvarchar(50)
as 
begin
Select p.PassengerId, p.Firstname,p.Lastname,t.TicketId,t.Issuedate  
	from Passenger p join Reservation r on p.PassengerId=r.PassengerId
	join Ticket t on r.ReservationId=t.ReservationId 
	where p.Lastname like '%'+@LastName+'%'
	order by t.Issuedate desc
end

