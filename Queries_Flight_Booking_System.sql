-- query 1:( To automatically reject baggage entries that exceed the 20kg free allowance without appropriate baggage fee in Baggage table.)
Create trigger PreventOverweightBaggageWithoutFee
on Baggage
instead of insert
as
begin
    If exists (
        select 1 
        from inserted 
        where BaggageWeight > 20 AND BaggageFee < (BaggageWeight - 20) * 100
    )
    begin
        raiserror('Overweight baggage must include appropriate additional fee.', 16, 1)
        rollback transaction
        return
    end

    -- If all good, insert the baggage
    Insert into Baggage (TicketId, BaggageWeight, BaggageStatus, BaggageFee)
    Select TicketId, BaggageWeight, BaggageStatus, BaggageFee
    from inserted
end;

-- query 2(Find passengers who spent more than £1000 (fare + services) in total.)
Select 
    P.PNR,
    P.FirstName,
    P.LastName,
    SUM(T.Fare + ISNULL(A.TotalAdditionalFare, 0)) as TotalSpent
from Passenger P
join Reservation R on P.PassengerId = R.PassengerId
join Ticket T on R.ReservationId = T.ReservationId
left join AdditionalServices A on T.TicketId = A.TicketId
group by P.PNR, P.FirstName, P.LastName
having SUM(T.Fare + ISNULL(A.TotalAdditionalFare, 0)) > 1000;