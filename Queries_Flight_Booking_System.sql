-- d) Update the details for a passenger that has booked a flight before.
Create procedure UpdatePassengerDetails
    @PassengerId int,
    @FirstName nvarchar(50),
    @LastName nvarchar(50),
    @Email nvarchar(50),
    @MealPreference nvarchar(15)
as
begin
    if exists (Select 1 from Reservation where PassengerId = @PassengerId)
    begin
        update Passenger
        set FirstName = @FirstName,
            LastName = @LastName,
            Email = @Email,
            MealPreference = @MealPreference
        where PassengerId = @PassengerId;
    end
    else
	begin
        print 'Passenger has no reservations and cannot be updated.';
    end
end;

